// Engine de Renderização e Pesquisa no DOM
document.addEventListener("DOMContentLoaded", () => {
  const scriptsList = document.getElementById("scripts-list");
  const scriptCounter = document.getElementById("script-counter");
  const searchInput = document.getElementById("search-input");
  const filterBtns = document.querySelectorAll(".pill-btn");
  const toast = document.getElementById("toast");
  const toastMessage = document.getElementById("toast-message");

  let currentCategory = "all";
  let currentSearch = "";

  function renderScripts() {
    scriptsList.innerHTML = "";
    
    let filtered = SCRIPTS_DATA.filter(item => {
      const matchCat = currentCategory === "all" || item.category === currentCategory;
      const q = currentSearch.toLowerCase();
      const matchSearch = item.title.toLowerCase().includes(q) || 
                          item.content.toLowerCase().includes(q) || 
                          item.categoryName.toLowerCase().includes(q);
      return matchCat && matchSearch;
    });

    scriptCounter.innerHTML = `Exibindo <strong>${filtered.length}</strong> de ${SCRIPTS_DATA.length} scripts`;

    if (filtered.length === 0) {
      scriptsList.innerHTML = `<div class="no-results">Nenhum script encontrado para "<strong>${currentSearch}</strong>".</div>`;
      return;
    }

    filtered.forEach(script => {
      const card = document.createElement("div");
      card.className = "script-card";
      
      card.innerHTML = `
        <div class="script-card-header">
          <span class="script-category-tag">${script.categoryName}</span>
        </div>
        <h3 class="script-title">${script.title}</h3>
        ${script.tip ? `<div class="script-strategy-box">💡 <strong>Dica de Uso:</strong> ${script.tip}</div>` : ""}
        <div class="script-content-box">${escapeHtml(script.content)}</div>
        <button class="btn-copy" data-id="${script.id}">
          <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><rect width="14" height="14" x="8" y="8" rx="2" ry="2"/><path d="M4 16c-1.1 0-2-.9-2-2V4c0-1.1.9-2 2-2h10c1.1 0 2 .9 2 2"/></svg>
          <span>Copiar Script</span>
        </button>
      `;

      scriptsList.appendChild(card);
    });

    // Attach copy click handlers
    document.querySelectorAll(".btn-copy").forEach(btn => {
      btn.addEventListener("click", (e) => {
        const id = btn.getAttribute("data-id");
        const found = SCRIPTS_DATA.find(s => s.id === id);
        if (found) {
          navigator.clipboard.writeText(found.content).then(() => {
            showToast("Script copiado com sucesso!");
          }).catch(err => {
            showToast("Erro ao copiar script.");
          });
        }
      });
    });
  }

  function escapeHtml(str) {
    return str.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  function showToast(msg) {
    toastMessage.textContent = msg;
    toast.classList.add("is-visible");
    setTimeout(() => {
      toast.classList.remove("is-visible");
    }, 2500);
  }

  // Filter Buttons
  filterBtns.forEach(btn => {
    btn.addEventListener("click", () => {
      filterBtns.forEach(b => b.classList.remove("is-active"));
      btn.classList.add("is-active");
      currentCategory = btn.getAttribute("data-category");
      renderScripts();
    });
  });

  // Search Input
  searchInput.addEventListener("input", (e) => {
    currentSearch = e.target.value;
    renderScripts();
  });

  // Initial Render
  renderScripts();
});
