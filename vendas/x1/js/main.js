document.addEventListener('DOMContentLoaded', () => {
  const searchInput = document.getElementById('search-input');
  const filterPills = document.querySelectorAll('.pill-btn');
  const scriptsContainer = document.getElementById('scripts-list');
  const scriptCounter = document.getElementById('script-counter');
  const toast = document.getElementById('toast');

  let currentCategory = 'all';
  let searchQuery = '';

  // Render Scripts Filtered
  function renderScripts() {
    const filtered = SCRIPTS_DATA.filter(script => {
      const matchesCategory = currentCategory === 'all' || script.category === currentCategory;
      const matchesSearch = searchQuery === '' || 
        script.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
        script.content.toLowerCase().includes(searchQuery.toLowerCase()) ||
        script.tip.toLowerCase().includes(searchQuery.toLowerCase());
      return matchesCategory && matchesSearch;
    });

    scriptCounter.textContent = `Exibindo ${filtered.length} de ${SCRIPTS_DATA.length} scripts de vendas`;

    if (filtered.length === 0) {
      scriptsContainer.innerHTML = `
        <div class="empty-state">
          <div class="empty-icon">🔍</div>
          <p>Nenhum script encontrado para "${searchQuery}".</p>
          <small>Tente buscar por termos como "caro", "pix", "canva" ou "abordagem".</small>
        </div>
      `;
      return;
    }

    scriptsContainer.innerHTML = filtered.map(script => `
      <div class="script-card" id="${script.id}">
        <div class="script-card-header">
          <span class="script-category-tag">${script.categoryName}</span>
        </div>
        <h3 class="script-title">${escapeHTML(script.title)}</h3>
        <div class="script-strategy-box">
          💡 <strong>Dica de Vendas:</strong> ${escapeHTML(script.tip)}
        </div>
        <div class="script-content-box" id="content-${script.id}">${escapeHTML(script.content)}</div>
        <button type="button" class="btn-copy" onclick="copyScriptText('${script.id}')">
          <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round">
            <rect x="9" y="9" width="13" height="13" rx="2" ry="2"></rect>
            <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"></path>
          </svg>
          <span>Copiar Mensagem Pronta</span>
        </button>
      </div>
    `).join('');
  }

  // Filter Pill Click Handler
  filterPills.forEach(pill => {
    pill.addEventListener('click', () => {
      filterPills.forEach(p => p.classList.remove('is-active'));
      pill.classList.add('is-active');
      currentCategory = pill.dataset.category;
      renderScripts();
    });
  });

  // Search Input Handler
  searchInput.addEventListener('input', (e) => {
    searchQuery = e.target.value.trim();
    renderScripts();
  });

  // Initial Render
  renderScripts();
});

// Global Function to Copy Script Content to Clipboard
function copyScriptText(scriptId) {
  const contentElement = document.getElementById(`content-${scriptId}`);
  if (!contentElement) return;

  const textToCopy = contentElement.innerText || contentElement.textContent;

  navigator.clipboard.writeText(textToCopy).then(() => {
    showToast('Texto copiado com sucesso! Cole no WhatsApp da cliente 😉');
  }).catch(err => {
    // Fallback for older browsers
    const textarea = document.createElement('textarea');
    textarea.value = textToCopy;
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.select();
    try {
      document.execCommand('copy');
      showToast('Texto copiado com sucesso! Cole no WhatsApp da cliente 😉');
    } catch (e) {
      alert('Erro ao copiar texto. Selecione manualmente.');
    }
    document.body.removeChild(textarea);
  });
}

// Toast Alert Manager
function showToast(message) {
  const toast = document.getElementById('toast');
  const toastMessage = document.getElementById('toast-message');
  if (!toast || !toastMessage) return;

  toastMessage.textContent = message;
  toast.classList.add('is-visible');

  setTimeout(() => {
    toast.classList.remove('is-visible');
  }, 2800);
}

// Helper to escape HTML characters
function escapeHTML(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
